/**
 * Hardware Compatibility Lab — Matrix Publisher
 *
 * Produces a signed, versioned JSON snapshot of the entire compatibility matrix.
 * This is the commercial deliverable — publishable on the Sentinel Grid website
 * or shared with enterprise prospects as proof of device support.
 *
 * The checksum field (SHA-256 of the entries array) provides tamper evidence.
 */

import { createHash } from "node:crypto";
import type { CompatibilityMatrixSnapshot } from "../domain/compatibility-lab.types.js";
import type { LabMatrixStore } from "../services/lab-matrix.store.js";

export class MatrixPublisher {
  constructor(
    private readonly store: LabMatrixStore,
    private readonly sentinelVersion: string = "0.1.0",
  ) {}

  /**
   * Produce a signed snapshot of the full matrix.
   * Optionally filter to a subset of entries.
   */
  publish(options?: {
    vendorFilter?: string;
    onlyCertified?: boolean;
  }): CompatibilityMatrixSnapshot {
    let entries = this.store.list();

    if (options?.vendorFilter) {
      entries = entries.filter(
        (e) => e.target.vendor === options.vendorFilter,
      );
    }

    if (options?.onlyCertified) {
      entries = entries.filter((e) =>
        e.overallRating === "CERTIFIED" || e.overallRating === "COMPATIBLE",
      );
    }

    const checksum = createHash("sha256")
      .update(JSON.stringify(entries))
      .digest("hex");

    return {
      schemaVersion: 1,
      sentinelVersion: this.sentinelVersion,
      publishedAt: new Date().toISOString(),
      entryCount: entries.length,
      entries,
      checksum,
    };
  }

  /**
   * Render the snapshot as a formatted JSON string suitable for download.
   */
  toJson(snapshot: CompatibilityMatrixSnapshot): string {
    return JSON.stringify(snapshot, null, 2);
  }

  /**
   * Render a compact Markdown summary for the compatibility matrix —
   * suitable for embedding in documentation or a website.
   */
  toMarkdown(snapshot: CompatibilityMatrixSnapshot): string {
    const lines: string[] = [
      `# Sentinel Grid Hardware Compatibility Matrix`,
      ``,
      `> Generated by Sentinel Grid v${snapshot.sentinelVersion}  `,
      `> Published: ${snapshot.publishedAt}  `,
      `> Entries: ${snapshot.entryCount}  `,
      `> Checksum (SHA-256): \`${snapshot.checksum}\``,
      ``,
      `## Rating Legend`,
      ``,
      `| Rating | Meaning |`,
      `|---|---|`,
      `| ✅ CERTIFIED | All 8 features pass or N/A |`,
      `| 🟢 COMPATIBLE | ≥5 features pass, Live + Substream both pass |`,
      `| 🟡 LIMITED | Live/Substream pass, but some other features fail |`,
      `| ❌ INCOMPATIBLE | Live or Substream fail, or <3 features pass |`,
      `| — UNTESTED | No tests run yet |`,
      ``,
      `## Matrix`,
      ``,
      `| Vendor | Model | Firmware | Live | Sub | Playback | Events | PTZ | HDD | Retention | Reboot | Rating |`,
      `|---|---|---|---|---|---|---|---|---|---|---|---|`,
    ];

    const statusIcon: Record<string, string> = {
      PASS: "✅",
      FAIL: "❌",
      PARTIAL: "⚠️",
      NA: "N/A",
      NOT_TESTED: "—",
    };

    const ratingIcon: Record<string, string> = {
      CERTIFIED: "✅ CERTIFIED",
      COMPATIBLE: "🟢 COMPATIBLE",
      LIMITED: "🟡 LIMITED",
      INCOMPATIBLE: "❌ INCOMPATIBLE",
      UNTESTED: "— UNTESTED",
    };

    const features = ["LIVE", "SUBSTREAM", "PLAYBACK", "EVENTS", "PTZ", "HDD_HEALTH", "RETENTION", "REBOOT"] as const;

    for (const entry of snapshot.entries) {
      const cells = features.map((f) => {
        const status = entry.results[f]?.status ?? "NOT_TESTED";
        return statusIcon[status] ?? "—";
      });

      lines.push(
        `| ${entry.target.vendor} | ${entry.target.modelId} | ${entry.target.firmwareVersion} | ${cells.join(" | ")} | ${ratingIcon[entry.overallRating] ?? entry.overallRating} |`,
      );
    }

    lines.push("");
    return lines.join("\n");
  }
}
